/**
 * Response Processor - configuration types.
 *
 * A universal, provider-agnostic post-processing layer: every model response (combo or
 * direct, streaming or not) is scanned for operator-defined matches and rewritten before
 * it reaches the client. The rules are declarative and safe: literal matching by default,
 * optional regex behind an explicit opt-in, bounded pattern length and a bounded holdback
 * window so a streaming response never loses or duplicates text.
 */

/** What to do when a rule matches. */
export type ResponseProcessorAction = "replace" | "remove" | "replace-whole-response";

/**
 * Where a rule is allowed to match.
 * - `anywhere`: normal substring/regex match anywhere in the text.
 * - `start`: the match must begin at the start of the (trimmed) text.
 * - `whole-response`: the whole (trimmed) text must match; the replacement replaces it.
 */
export type ResponseProcessorAnchor = "anywhere" | "start" | "whole-response";

/** Guard conditions that must all hold before a rule is applied. */
export interface ResponseProcessorCondition {
  /** `contains` requires the value to be present, `not-contains` requires it to be absent. */
  type: "contains" | "not-contains";
  value: string;
  caseSensitive?: boolean;
}

export interface ResponseProcessorRule {
  /** Stable identifier (generated by the dashboard). */
  id: string;
  /** Human label shown in the dashboard list. */
  label?: string;
  enabled: boolean;
  /** Literal text or (with `matchType: "regex"`) a regular-expression source. */
  match: string;
  matchType?: "literal" | "regex";
  caseSensitive?: boolean;
  anchor?: ResponseProcessorAnchor;
  action: ResponseProcessorAction;
  /** Replacement text. Ignored for `remove`; defaults to empty for `replace`. */
  replaceWith?: string;
  /** Conditions that gate the rule; all must pass. */
  conditions?: ResponseProcessorCondition[];
  /**
   * Compare with runs of whitespace collapsed to one space on both sides. Lets a rule catch
   * a banner that the model wrapped across lines without writing a regex.
   */
  collapseWhitespace?: boolean;
  /**
   * Longest text this rule can match. Used for the streaming holdback window. Literal rules
   * derive it from the pattern; regex rules that can match more must declare it.
   */
  maxMatchLength?: number;
}

export interface ResponseProcessorConfig {
  /** Master switch. When false the layer is a no-op and no transform is piped. */
  enabled: boolean;
  /** Rules applied in order; later rules see the output of earlier ones. */
  rules: ResponseProcessorRule[];
}

